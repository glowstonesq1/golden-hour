// Writes worker/src/top-sites.js from the Tranco top-sites list (https://tranco-list.eu, CC BY 4.0 data).
// Usage: node worker/scripts/top-sites.mjs [count]   (default 10000; a bigger list makes a bigger worker)
import { writeFile } from 'node:fs/promises';
import { inflateRawSync } from 'node:zlib';

const count = Number(process.argv[2] || 10000);
const res = await fetch('https://tranco-list.eu/top-1m.csv.zip');
if (!res.ok) throw new Error(`Tranco download failed: ${res.status}`);
const zip = Buffer.from(await res.arrayBuffer());
// One-entry zip: the local header is followed by the deflated CSV.
const nameLen = zip.readUInt16LE(26);
const extraLen = zip.readUInt16LE(28);
const compSize = zip.readUInt32LE(18);
const csv = inflateRawSync(zip.subarray(30 + nameLen + extraLen, 30 + nameLen + extraLen + compSize)).toString();
const sites = csv.split('\n').slice(0, count).map((l) => l.split(',')[1]?.trim()).filter(Boolean);
await writeFile(new URL('../src/top-sites.js', import.meta.url),
  `// Generated by worker/scripts/top-sites.mjs from the Tranco list on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\nexport const TOP_SITES = new Set(${JSON.stringify(sites)});\n`);
console.log(`Wrote ${sites.length} sites.`);
